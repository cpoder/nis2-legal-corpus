#!/usr/bin/env node
/**
 * Generates legal-sources/INDEX.md from the `<!-- meta: ... -->` lines carried
 * by each `##` section of legal-sources/<country>.md.
 *
 * The per-country files answer "what do we know about Polish law". They cannot
 * answer "where has this class of defect appeared before", because a pattern
 * that spans two countries lives in two files and is invisible. That second
 * question is the one that saves time, so it gets a generated view.
 *
 * The taxonomy below mirrors the one in the Reglyze repository; the corpus
 * build fails if the two drift apart.
 *
 * Usage: node tools/build-index.mjs  (add --check to fail instead of writing)
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "legal-sources");
const OUT = join(DIR, "INDEX.md");

export const THEMES = [
  "statute",
  "scoping",
  "registration",
  "incident",
  "supply-chain",
  "governance",
  "sanctions",
  "framework",
  "documents",
];

export const TYPES = [
  // reference
  "reference",
  "delivery",
  "needs-check",
  "lead",
  // defects
  "fabrication",
  "stale-statute",
  "wrong-citation",
  "law-misread",
  "deadline-model",
  "scope-error",
  "overclaim",
  "status-error",
  "surface-inconsistency",
  "i18n",
  "test-pinned",
];

export const DEFECT_TYPES = new Set(
  TYPES.filter((t) => !["reference", "delivery", "needs-check", "lead"].includes(t)),
);

export const SURFACES = [
  "data",
  "prompt",
  "doc-gen",
  "ui",
  "marketing",
  "mcp",
  "i18n",
  "test",
  "docs",
];

const META = /^<!--\s*meta:\s*(.+?)\s*-->$/;

/** Parse every annotated section out of the country files. */
export function collect(dir = DIR) {
  const entries = [];
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .filter((f) => !["INDEX.md", "README.md", "TAXONOMY.md"].includes(f))
    .sort();

  for (const file of files) {
    const country = file.replace(/\.md$/, "");
    const lines = readFileSync(join(dir, file), "utf-8").split("\n");
    let current = null;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (line.startsWith("## ")) {
        current = { country, file, title: line.slice(3).trim(), line: i + 1, meta: null };
        entries.push(current);
        continue;
      }
      if (!current || current.meta) continue;
      const m = line.trim().match(META);
      if (!m) continue;
      const meta = {};
      for (const pair of m[1].split(";")) {
        const [k, v] = pair.split("=").map((s) => s?.trim());
        if (k) meta[k] = v ?? "";
      }
      current.meta = {
        themes: (meta.theme ?? "").split(",").map((s) => s.trim()).filter(Boolean),
        types: (meta.type ?? "").split(",").map((s) => s.trim()).filter(Boolean),
        date: meta.date ?? "",
        surfaces: (meta.surfaces ?? "").split(",").map((s) => s.trim()).filter(Boolean),
        guard: meta.guard ?? "none",
        // Deliberate absence of a guard, with the reason: "not done yet" and
        // "we looked and it cannot be mechanised" are different states.
        debt: meta.debt ?? "",
      };
    }
  }
  return entries;
}

const esc = (s) => s.replace(/\|/g, "\\|");
const anchor = (e) => `[${e.country}](${e.file}): ${esc(e.title)}`;

export function render(entries) {
  const annotated = entries.filter((e) => e.meta);
  const defects = annotated.filter((e) => e.meta.types.some((t) => DEFECT_TYPES.has(t)));

  const out = [];
  out.push("# Cross-cutting index of the legal sources");
  out.push("");
  out.push(
    "> GENERATED by `node tools/build-index.mjs`. **Do not edit by hand**: change the `<!-- meta: -->` line of the section concerned. Vocabulary: [TAXONOMY.md](TAXONOMY.md).",
  );
  out.push("");
  out.push(
    `${annotated.length} annotated sections out of ${entries.length}, in ${new Set(annotated.map((e) => e.country)).size} files. ${defects.length} record a corrected defect.`,
  );
  out.push("");

  out.push("## By theme");
  out.push("");
  for (const theme of THEMES) {
    const hits = annotated.filter((e) => e.meta.themes.includes(theme));
    if (!hits.length) continue;
    out.push(`### ${theme} (${hits.length})`);
    out.push("");
    out.push("| File | Section | Type | Date |");
    out.push("|---|---|---|---|");
    for (const e of hits.sort((a, b) => a.country.localeCompare(b.country))) {
      out.push(`| ${e.country} | [${esc(e.title)}](${e.file}) | ${e.meta.types.join(", ")} | ${e.meta.date} |`);
    }
    out.push("");
  }

  out.push("## By type of defect");
  out.push("");
  out.push(
    "This is the view the per-country layout cannot give. A class of defect that appears in several countries is a class that will appear again.",
  );
  out.push("");
  for (const type of TYPES.filter((t) => DEFECT_TYPES.has(t))) {
    const hits = annotated.filter((e) => e.meta.types.includes(type));
    if (!hits.length) continue;
    const countries = new Set(hits.map((e) => e.country));
    out.push(`### ${type}: ${hits.length} occurrence${hits.length > 1 ? "s" : ""} in ${countries.size} file${countries.size > 1 ? "s" : ""}`);
    out.push("");
    out.push("| File | Section | Surfaces | Guard |");
    out.push("|---|---|---|---|");
    for (const e of hits.sort((a, b) => a.country.localeCompare(b.country))) {
      const g = e.meta.guard === "none" ? "none" : `\`${e.meta.guard.split("/").pop()}\``;
      out.push(`| ${e.country} | [${esc(e.title.slice(0, 70))}](${e.file}) | ${e.meta.surfaces.join(", ") || "-"} | ${g} |`);
    }
    out.push("");
  }

  out.push("## By product surface");
  out.push("");
  out.push("| Surface | Defects |");
  out.push("|---|---|");
  for (const s of SURFACES) {
    const n = defects.filter((e) => e.meta.surfaces.includes(s)).length;
    if (n) out.push(`| ${s} | ${n} |`);
  }
  out.push("");

  const unguarded = defects.filter((e) => e.meta.guard === "none" && !e.meta.debt);
  const debt = defects.filter((e) => e.meta.guard === "none" && e.meta.debt);
  const needsCheck = annotated.filter((e) => e.meta.types.includes("needs-check"));
  const leads = annotated.filter((e) => e.meta.types.includes("lead"));
  out.push("## Open items");
  out.push("");
  out.push(`### Corrected defects without a guard (${unguarded.length})`);
  out.push("");
  out.push(...(unguarded.length ? unguarded.map((e) => `- ${anchor(e)}`) : ["None."]));
  out.push("");
  out.push(`### Accepted debt: no guard, and why (${debt.length})`);
  out.push("");
  out.push(...(debt.length ? debt.map((e) => `- ${anchor(e)}: _${e.meta.debt}_`) : ["None."]));
  out.push("");
  out.push(`### Facts not yet verified (${needsCheck.length})`);
  out.push("");
  out.push(...(needsCheck.length ? needsCheck.map((e) => `- ${anchor(e)}`) : ["None."]));
  out.push("");
  out.push(`### Leads not yet followed (${leads.length})`);
  out.push("");
  out.push(...(leads.length ? leads.map((e) => `- ${anchor(e)}`) : ["None."]));
  out.push("");

  const missing = entries.filter((e) => !e.meta);
  if (missing.length) {
    out.push(`### Sections without a meta line (${missing.length})`);
    out.push("");
    for (const e of missing) out.push(`- ${e.file}:${e.line}: ${e.title}`);
    out.push("");
  }

  return out.join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const entries = collect();
  const body = render(entries);
  if (process.argv.includes("--check")) {
    let existing = "";
    try {
      existing = readFileSync(OUT, "utf-8");
    } catch {
      existing = "";
    }
    if (existing.trim() !== body.trim()) {
      console.error("legal-sources/INDEX.md is stale: run `node tools/build-index.mjs`.");
      process.exit(1);
    }
    console.log("INDEX.md up to date.");
  } else {
    writeFileSync(OUT, body + "\n");
    console.log(`INDEX.md written: ${entries.filter((e) => e.meta).length}/${entries.length} sections annotated.`);
  }
}
